const assert = require('node:assert/strict');
const fs = require('node:fs');
const core = require('../assets/js/resident-area-core');
const view = require('../assets/js/resident-area-view');
const now = new Date('2026-11-13T10:00:00Z');
const fact = {id: 'real-result', content_origin: 'verified', status: 'published', date: '2026-10-01', source_url: 'https://example.org/fact', tos_slug: 'one', title: 'Реальный результат'};
const need = {...fact, id: 'real-need', source_checked_at: '2026-11-12'};
const event = {...fact, id: 'real-event', date: '2026-11-15', source_checked_at: '2026-11-12', title: 'Встреча, соседи; двор', description: 'Первая строка\nВторая строка', place: 'Площадка', time: ''};
const data = {toses: [{slug: 'one', name: 'Первый', location: 'с. Ёлки', boundaries: 'улица Лесная'}, {slug: 'two', name: 'Второй'}], done: [fact, {...fact, id: 'request', content_origin: 'request'}, {...fact, id: 'future', date: '2026-12-01'}, {...fact, id: 'invalid', date: '2026-02-30'}, {...fact, id: 'unsafe', source_url: 'javascript:alert(1)'}, {...fact, id: 'other', tos_slug: 'two'}], news: [], needs: [need, {...need, id: 'old-need', source_checked_at: '2026-07-01'}, {...need, id: 'request-need', content_origin: 'request'}, {...need, id: 'idea-need', content_origin: 'editorial', tos_slug: ''}], events: [event, {...event, id: 'common-event', tos_slug: ''}, {...event, id: 'old-event', date: '2026-11-12'}, {...event, id: 'draft', status: 'draft'}, {...event, id: 'idea-event', content_origin: 'editorial'}], scenarios: []};
assert.equal(core.today('2026-11-12T21:30:00Z'), '2026-11-13', 'Dates use Moscow, not server timezone');
assert.equal(core.checkedDate('2026-02-30'), '');
assert.equal(core.safeUrl('javascript:alert(1)'), '');
assert.equal(core.findArea(data.toses, '../one'), null);
assert.equal(core.findArea(data.toses, 'missing'), null);
assert.deepEqual(core.searchAreas(data.toses, 'елки лесная').map(x => x.slug), ['one']);
assert.deepEqual(core.searchAreas(data.toses, 'ТОС Первый').map(x => x.slug), ['one']);
const model = core.overview(data, 'one', now);
assert.deepEqual(model.results.map(x => x.id), ['real-result'], 'Only sourced factual, dated results of selected TOS');
assert.deepEqual(model.localEvents.map(x => x.id), ['real-event']);
assert.deepEqual(model.commonEvents.map(x => x.id), ['common-event']);
assert.equal(core.overview({...data, events: [{...event, source_checked_at: ''}]}, 'one', now).localEvents.length, 0, 'A date and generic source link do not confirm an announcement');
assert.equal(core.overview({...data, events: [{...event, source_checked_at: '2026-09-01'}]}, 'one', now).localEvents.length, 0, 'Old checks do not support current announcements');
assert.equal(model.needs.length, 2);
assert.equal(model.requests.length, 1);
assert.equal(model.ideas.length, 1);
assert.equal(core.needState(need, now), 'current');
assert.equal(core.needState({...need, source_checked_at: '2026-11-14'}, now), 'check', 'Future checks are not evidence');
assert.equal(core.needState({...need, source_checked_at: '', date: '2026-11-13'}, now), 'check', 'Record date is not confirmation of need');
assert.equal(core.needState({...need, valid_until: '2026-11-12'}, now), 'expired');
assert.equal(core.needState({...need, content_origin: 'request'}, now), 'request');
assert.equal(core.helpKind({need_type: 'Материалы'}), 'materials');
assert.equal(core.helpKind({need_type: 'Волонтёры'}), 'time');
assert.equal(core.helpKind({need_type: 'Фото и информация'}), 'information');
assert.equal(core.areaUrl('one', 'materials'), '/residents/my-area/?tos=one&help=materials');
assert(!core.areaUrl('../one', 'bad').includes('tos='));
const html = view.dashboard({...data, toses: [{...data.toses[0], name: '<img src=x onerror=alert(1)>'}]}, 'one', 'all', now);
assert(!html.includes('<img src=x'), 'Catalog text cannot create executable HTML');
assert(html.includes('&lt;img'));
assert(!html.includes('href="javascript:'));
assert(!html.includes('href=""'));
const ics = core.eventCalendar({...event, title: 'Встреча\r\nBEGIN:VALARM', description: 'Длинная русская строка '.repeat(30)}, now);
assert(ics.includes('DTSTART;VALUE=DATE:20261115\r\nDTEND;VALUE=DATE:20261116'));
assert(!ics.includes('\r\nBEGIN:VALARM'), 'Newlines in data cannot inject calendar components');
assert(!ics.includes('TRIGGER:'), 'No fabricated alarms');
assert(ics.replace(/\r\n /g, '').includes('Время в объявлении не указано.'));
assert(ics.split('\r\n').every(line => Buffer.byteLength(line) <= 75), 'Lines fold at 75 UTF-8 octets');
assert.equal(ics.replace(/\r\n /g, '').includes('Длинная русская строка '.repeat(30).trim()), true);
assert.throws(() => core.eventCalendar({...event, date: '2026-02-30'}, now));
const actual = require('./generate_resident_area').dataForPage();
assert.equal(actual.toses.length, JSON.parse(fs.readFileSync('data/toses.json')).filter(core.publicItem).length);
assert(actual.toses.every(item => !Object.hasOwn(item, 'phones') && !Object.hasOwn(item, 'contacts_raw')), 'No additional personal-contact dataset');
const page = fs.readFileSync('residents/my-area/index.html', 'utf8');
assert.equal((page.match(/<li><a href="\/tos\//g) || []).length, actual.toses.length, 'Complete directory without scripts');
for (const slug of actual.toses.map(item => item.slug)) {
  assert(fs.readFileSync('tos/' + slug + '/index.html', 'utf8').includes('href="/residents/my-area/?tos=' + slug + '"'));
}
assert(page.includes('rel="canonical" href="https://tosborisoglebsk.ru/residents/my-area/"'));
console.log('Resident area: truthful scope, need freshness, Moscow dates, safe rendering, calendar export and no-script directory passed');

const vkNews = {...fact, id:'vk-9-4', content_origin:'editorial', imported_from:'vk', source_url:'https://vk.com/wall-9_4'};
assert.equal(core.overview({...data,news:[vkNews]},'one',now).news.length,1);
assert.equal(core.overview({...data,news:[{...vkNews,source_url:'https://example.org/fake'}]},'one',now).news.length,0);
assert(view.dashboard({...data,news:[vkNews]},'one','all',now).includes('Из сообщества ВКонтакте'));
