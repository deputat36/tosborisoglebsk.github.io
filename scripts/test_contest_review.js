'use strict';
const assert=require('node:assert/strict');
const review=require('../assets/js/contest-review-core');
const data=require('../data/contest_checklists.json');
const opportunities=require('../data/grants.json').filter(row=>row.status!=='draft'&&['grant','award'].includes(row.opportunity_type));
const available=review.contexts(data.checklists,opportunities);
const pfki=available.find(row=>row.scope==='pfki-2027-second');
const local=available.find(row=>row.scope==='fond-borisoglebsk-second-2026');
const checked=new Map([[pfki.scope+'|'+pfki.list.items[0].id,true],[local.scope+'|'+local.list.items[0].id,true]]);
const saved=review.snapshot(available,pfki.scope,checked,new Date('2026-11-14T18:00:00Z'));
assert(Buffer.byteLength(JSON.stringify(saved))<=review.MAX_BYTES,'the current catalogue produces a file that can be opened again');
let restored=review.restore(review.parse(JSON.stringify(saved)),available);
assert.deepEqual(restored.checked,checked);
assert.equal(restored.opportunity,pfki.scope);
assert.deepEqual(restored.changed,[]);
const changed=structuredClone(available);
changed.find(row=>row.scope===pfki.scope).opportunity.source_documents[0].url+='?new-edition=1';
restored=review.restore(saved,changed);
assert.equal(restored.checked.has(pfki.scope+'|'+pfki.list.items[0].id),false,'changed official documents require a new review');
assert.equal(restored.checked.has(local.scope+'|'+local.list.items[0].id),true,'another programme keeps its marks');
assert.equal(restored.changed.length,1);
const other=available.find(row=>row.scope!=='general'&&row.scope!==local.scope&&row.list.id==='general');
assert(other);
assert.equal(restored.checked.has(other.scope+'|'+local.list.items[0].id),false,'programmes using the general questions do not share marks');
assert.throws(()=>review.parse('{broken'),/прочитать/);
assert.throws(()=>review.parse(' '.repeat(review.MAX_BYTES+1)),/256/);
assert.throws(()=>review.normalize({...saved,kind:'tos-project-workspace'}),/файл проверки/);
assert.throws(()=>review.normalize({...saved,version:999}),/файл проверки/);
assert.throws(()=>review.normalize({...saved,reviews:[saved.reviews[0],saved.reviews[0]]}),/повторяющийся/);
assert.throws(()=>review.normalize({...saved,reviews:[{...saved.reviews[0],checked:['<script>']}]}),/неподходящий/);
const unknown=structuredClone(saved);unknown.opportunity='removed-season';unknown.reviews.push({scope:'removed-season',checklist:'general',revision:'old',checked:['problem']});
restored=review.restore(unknown,available);
assert.equal(restored.opportunity,'');assert(restored.unknown.includes('removed-season'));
assert.deepEqual(checked,review.restore(saved,available).checked,'parsing failed files never mutates existing state');
console.log('Contest review OK: portable marks, isolated programmes, changed documents, invalid files and removed seasons');
